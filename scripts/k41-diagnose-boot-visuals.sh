#!/usr/bin/env bash
# Read-only diagnostic collector for Hyprland startup/shutdown text leakage.
# Run as the logged-in desktop user, from the affected Hyprland session.
set -Eeuo pipefail
umask 077

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
STAMP="$(date -u +'%Y%m%dT%H%M%SZ')"
OUT="$ROOT/reports/boot-visual-diagnostics/$STAMP"
mkdir -p "$OUT"
REPORT="$OUT/report.txt"
: >"$REPORT"
chmod 0600 "$REPORT"

section() { printf '\n\n===== %s =====\n' "$*" >>"$REPORT"; }
run() {
  local title=$1; shift
  section "$title"
  if command -v "$1" >/dev/null 2>&1; then
    "$@" >>"$REPORT" 2>&1 || printf '[command exited %s]\n' "$?" >>"$REPORT"
  else
    printf '[not installed: %s]\n' "$1" >>"$REPORT"
  fi
}
filter_logs() {
  # Keep only Hyprland/session/display-manager/Plymouth-related journal lines.
  # Redact common personal/network identifiers before writing the report.
  grep -Ei 'hyprland|start-hyprland|welcome to hyprland|splash|plymouth|quickshell|qs\[' |
    tail -n 350 |
    sed -E \
      -e "s#${HOME//\//\\/}#<HOME>#g" \
      -e "s#${USER}#<USER>#g" \
      -e 's/[0-9]{1,3}(\.[0-9]{1,3}){3}/<IP-REDACTED>/g'
}

{
  printf 'K41 Boot Visual Diagnostic Report\n'
  printf 'Generated UTC: %s\n' "$STAMP"
  printf 'Collector: scripts/k41-diagnose-boot-visuals.sh\n'
  printf 'Mode: read-only; no service/configuration changes\n'
  printf 'Host: %s\n' "$(hostname 2>/dev/null || printf unknown)"
  printf 'User: %s\n' "$USER"
  printf 'Kernel: %s\n' "$(uname -r)"
} >>"$REPORT"

run "HYPRLAND VERSION" hyprctl version
run "HYPRLAND INSTANCES" hyprctl instances
run "HYPRLAND SYSTEM INFO" hyprctl systeminfo
run "HYPRLAND VISUAL OPTIONS" hyprctl getoption misc:disable_hyprland_logo
run "HYPRLAND SPLASH OPTION" hyprctl getoption misc:disable_splash_rendering
run "HYPRLAND WALLPAPER OPTION" hyprctl getoption misc:force_default_wallpaper
run "HYPRLAND BACKGROUND OPTION" hyprctl getoption misc:background_color
run "RELEVANT PROCESSES" pgrep -a -f 'Hyprland|start-hyprland|hyprpaper|quickshell|qs'
run "TTY1 GETTY UNIT" systemctl status getty@tty1.service --no-pager
run "PLYMOUTH UNIT STATES" systemctl list-units --all --no-pager 'plymouth*'
run "HYPRLAND CONFIG MARKERS" bash -c '
  f="$HOME/.config/hypr/hyprland.lua"
  if [[ -r "$f" ]]; then
    grep -n -A12 -B3 -E "K41 BOOT VISUAL SUPPRESSION|K41 ANIMATED BOOT SPLASH|hyprland.start|disable_splash_rendering|disable_hyprland_logo" "$f" || true
  else
    printf "Expected Lua config not readable: %s\n" "$f"
  fi
'
run "HYPRPAPER CONFIG SPLASH SETTINGS" bash -c '
  for f in "$HOME/.config/hypr/hyprpaper.conf" "$HOME/.config/hypr/hyprpaper.conf.d/"*.conf; do
    [[ -f "$f" ]] || continue
    printf -- "--- %s ---\n" "$f"
    grep -n -Ei "splash|preload|wallpaper" "$f" || true
  done
'
section "CURRENT BOOT JOURNAL — MATCHING LINES"
if command -v journalctl >/dev/null 2>&1; then
  journalctl -b --no-pager -o short-monotonic 2>&1 | filter_logs >>"$REPORT" || true
else
  printf '[journalctl not installed]\n' >>"$REPORT"
fi
section "PREVIOUS BOOT JOURNAL — MATCHING LINES (REBOOT/POWEROFF EVIDENCE)"
if command -v journalctl >/dev/null 2>&1; then
  journalctl -b -1 --no-pager -o short-monotonic 2>&1 | filter_logs >>"$REPORT" || true
else
  printf '[journalctl not installed]\n' >>"$REPORT"
fi
section "USER JOURNAL — MATCHING LINES"
if command -v journalctl >/dev/null 2>&1; then
  journalctl --user -b --no-pager -o short-monotonic 2>&1 | filter_logs >>"$REPORT" || true
fi

cat >"$OUT/README.txt" <<EOF
K41 boot visual diagnostic
==========================
File: report.txt

This report was generated by a read-only collector. It does not change
Hyprland, Plymouth, systemd, bootloader, LUKS, TPM2, or user configuration.

Review report.txt before pushing it to GitHub. Although common home paths,
usernames, and IPv4 addresses are redacted, logs can contain other identifying
or sensitive information. Remove anything private before committing.

Run from the repository root:
  bash scripts/k41-diagnose-boot-visuals.sh

Then inspect:
  $OUT/report.txt

Commit/push only the report directory for this diagnostic run.
EOF
chmod 0600 "$OUT/README.txt"

printf 'Diagnostic report created: %s\n' "$OUT/report.txt"
printf 'Review it for private information, then commit and push the report directory.\n'
