#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
SCRIPT="$ROOT/scripts/k41-configure-boot-experience.sh"

[[ -f $SCRIPT ]]
bash -n "$SCRIPT"
bash -n "$ROOT/scripts/k41-lock-caelestia-after-start.sh"
bash -n "$ROOT/scripts/k41-start-hyprland.sh"
bash -n "$ROOT/scripts/k41-enable-caelestia-autologin.sh"
bash -n "$ROOT/scripts/k41-plymouth-quit-after-lock.sh"
grep -Fq 'systemd-cryptenroll --tpm2-device=auto --tpm2-pcrs=7' "$SCRIPT"
! grep -Fq 'cryptsetup luksHeaderBackup' "$SCRIPT"
! grep -Fq 'Header backup path:' "$SCRIPT"
! grep -Fq '$header_backup' "$SCRIPT"
grep -Fq 'plymouth-set-default-theme k41' "$SCRIPT"
grep -Fq 'k41-install-animated-boot-splash.sh' "$SCRIPT"
grep -Fq 'HYPRLAND_CONFIG' "$SCRIPT"
grep -Fq 'k41-start-hyprland' "$SCRIPT"
grep -Fq 'hyprland-startup.log' "$ROOT/scripts/k41-start-hyprland.sh"
grep -Fq 'k41-start-hyprland' "$ROOT/scripts/k41-enable-caelestia-autologin.sh"
grep -Fq 'themes/plymouth/k41' "$SCRIPT"
grep -Fq 'plymouth-set-default-theme k41' "$ROOT/scripts/k41-install-plymouth-theme.sh"
grep -Fq 'quiet' "$SCRIPT"
grep -Fq 'splash' "$SCRIPT"
grep -Fq 'k41-plymouth-release.service' "$SCRIPT"
grep -Fq 'plymouth quit --retain-splash' "$SCRIPT"
grep -Fq 'k41-lock-handoff.conf' "$SCRIPT"
grep -Fq 'boot-lock-ready' "$SCRIPT"
grep -Fq 'ExecStartPre=/usr/bin/rm -f' "$SCRIPT"
grep -Fq 'mark_ready' "$ROOT/scripts/k41-lock-caelestia-after-start.sh"
grep -Fq 'systemctl stop getty@tty1.service' "$ROOT/scripts/k41-plymouth-quit-after-lock.sh"
! grep -Eq 'cryptsetup[[:space:]]+luksErase|--wipe-slot=all|wipefs[[:space:]]' "$SCRIPT"

printf 'PASS: boot-experience script syntax and safety invariants\n'
