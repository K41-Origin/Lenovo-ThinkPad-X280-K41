#!/usr/bin/env bash
set -Eeuo pipefail
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
bash -n "$ROOT/scripts/k41-install-plymouth-theme.sh"
grep -Fq 'ModuleName=script' "$ROOT/themes/plymouth/k41/k41.plymouth"
grep -Fq 'ScriptFile=/usr/share/plymouth/themes/k41/k41.script' "$ROOT/themes/plymouth/k41/k41.plymouth"
grep -Fq 'Window.SetBackgroundTopColor (0.0, 0.0, 0.0)' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'Plymouth.SetRefreshFunction(refresh_callback)' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'Plymouth.SetDisplayPasswordFunction(display_password_callback)' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'Plymouth.SetDisplayNormalFunction(display_normal_callback)' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'mkinitcpio -P' "$ROOT/scripts/k41-install-plymouth-theme.sh"
grep -Fq 'plymouth-reboot.service' "$ROOT/scripts/k41-install-plymouth-theme.sh"
grep -Fq 'plymouth-poweroff.service' "$ROOT/scripts/k41-install-plymouth-theme.sh"
grep -Fq 'reboot.target.wants' "$ROOT/scripts/k41-install-plymouth-theme.sh"
grep -Fq 'poweroff.target.wants' "$ROOT/scripts/k41-install-plymouth-theme.sh"
! grep -Eq 'systemd-cryptenroll|luksAddKey|luksRemoveKey|luksErase|wipe-slot' "$ROOT/scripts/k41-install-plymouth-theme.sh"

grep -Fq 'global.count = 12;' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'global.radius = 9;' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'Image.Text("K41", 0.8, 0.8, 0.8)' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'Image.Text("▯", 0.9, 0.9, 0.9)' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'global.rectangles[i].SetOpacity(opacity)' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'global.center_y + 10' "$ROOT/themes/plymouth/k41/k41.script"
grep -Fq 'readonly property int rectangleCount: 12' "$ROOT/config/quickshell/k41-boot-splash/shell.qml"
grep -Fq 'readonly property real ringRadius: 9' "$ROOT/config/quickshell/k41-boot-splash/shell.qml"
grep -Fq 'text: "K41"' "$ROOT/config/quickshell/k41-boot-splash/shell.qml"
grep -Fq 'width: 4' "$ROOT/config/quickshell/k41-boot-splash/shell.qml"
grep -Fq 'height: 10' "$ROOT/config/quickshell/k41-boot-splash/shell.qml"

printf 'PASS: K41 Plymouth theme static invariants\n'